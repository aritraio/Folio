export const INITIAL_NETWORTH_HISTORY = Array.from({ length: 12 }, (_, i) => {
  const date = subMonths(now, 11 - i);
  const monthKey = format(date, 'yyyy-MM');
  const label = format(date, 'MMM yy');
  const shortLabel = format(date, 'MMM');
  const progressRatio = i / 11;
  const assets = Math.round(24000 + progressRatio * 50000 + (i % 3) * 600);
  const liabilities = Math.round(2000 + progressRatio * 3770);
  const netWorth = assets - liabilities;
  return {
    monthKey,
    label,
    shortLabel,
    assets,
    liabilities,
    netWorth,
  };
});

